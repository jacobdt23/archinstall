def _rgb_to_hex(r: int, g: int, b: int) -> str:
    return f"#{max(0, min(255, r)):02x}{max(0, min(255, g)):02x}{max(0, min(255, b)):02x}"


def _hsv_to_hex(h: float, s: float, v: float) -> str:
    r, g, b = colorsys.hsv_to_rgb(h % 1.0, max(0.0, min(1.0, s)), max(0.0, min(1.0, v)))
    return _rgb_to_hex(int(r * 255), int(g * 255), int(b * 255))


def _hex_to_rgba_css(hex_color: str, alpha: float) -> str:
    h = hex_color.lstrip("#")
    r, g, b = int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16)
    return f"rgba({r}, {g}, {b}, {alpha:.2f})"


def extract_palette(image_path: Path) -> dict[str, str]:
    """Extract a cohesive dark-mode color palette from a wallpaper image (pywal-style)."""
    pb = GdkPixbuf.Pixbuf.new_from_file_at_scale(str(image_path), 72, 72, True)
    pixels = pb.get_pixels()
    n_channels = pb.get_n_channels()
    rowstride = pb.get_rowstride()
    width = pb.get_width()
    height = pb.get_height()

    # Quantize hue into 18 buckets (20 deg each) and track vibrancy + average hue
    hue_buckets: dict[int, list[tuple[float, float, float]]] = {}
    dark_hues: list[float] = []

    for y in range(height):
        row_offset = y * rowstride
        for x in range(width):
            idx = row_offset + x * n_channels
            r, g, b = pixels[idx] / 255.0, pixels[idx + 1] / 255.0, pixels[idx + 2] / 255.0
            h, s, v = colorsys.rgb_to_hsv(r, g, b)
            if v < 0.45 and s > 0.08:
                dark_hues.append(h)
            if s > 0.22 and 0.20 < v < 0.96:
                bucket = int(h * 18) % 18
                hue_buckets.setdefault(bucket, []).append((h, s, v))

    # Pick primary accent from the most vibrant populated hue bucket
    ranked = sorted(
        hue_buckets.items(),
        key=lambda kv: len(kv[1]) * (sum(c[1] * c[2] for c in kv[1]) / len(kv[1])),
        reverse=True,
    )

    if ranked:
        top_colors = ranked[0][1]
        h1 = sum(c[0] for c in top_colors) / len(top_colors)
        s1 = max(0.45, min(0.82, sum(c[1] for c in top_colors) / len(top_colors)))
        v1 = max(0.78, min(0.96, sum(c[2] for c in top_colors) / len(top_colors)))
    else:
        h1, s1, v1 = 0.74, 0.55, 0.92

    # Pick a distinct secondary accent (at least 2 buckets away)
    h2, s2, v2 = (h1 + 0.14) % 1.0, max(0.48, s1 * 0.92), max(0.80, v1)
    for bucket, cols in ranked[1:]:
        cand_h = sum(c[0] for c in cols) / len(cols)
        dist = min(abs(cand_h - h1), 1.0 - abs(cand_h - h1))
        if dist >= 0.11:
            h2 = cand_h
            s2 = max(0.48, min(0.82, sum(c[1] for c in cols) / len(cols)))
            v2 = max(0.80, min(0.96, sum(c[2] for c in cols) / len(cols)))
            break

    base_h = (sum(dark_hues) / len(dark_hues)) if dark_hues else h1

    return {
        "name": image_path.stem,
        "wallpaper": str(image_path),
        "bg": _hsv_to_hex(base_h, 0.22, 0.16),
        "bg_alt": _hsv_to_hex(base_h, 0.24, 0.12),
        "surface": _hsv_to_hex(base_h, 0.22, 0.26),
        "fg": "#f8f8f2",
        "muted": _hsv_to_hex(base_h, 0.25, 0.52),
        "accent": _hsv_to_hex(h1, s1, v1),
        "accent2": _hsv_to_hex(h2, s2, v2),
        "cyan": _hsv_to_hex((h1 + 0.35) % 1.0, 0.45, 0.92),
        "green": "#50fa7b",
        "orange": "#ffb86c",
        "red": "#ff5555",
        "yellow": "#f1fa8c",
    }


