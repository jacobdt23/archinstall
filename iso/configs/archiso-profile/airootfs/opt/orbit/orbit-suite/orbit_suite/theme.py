def apply_live(palette: dict[str, str]) -> None:
    """Apply wallpaper, Hyprland border colors, and restart Orbit Shell live."""
    write_theme_files(palette)

    wall = palette.get("wallpaper", "")
    if wall and Path(wall).is_file():
        hp_conf = Path.home() / ".config" / "hypr-standalone" / "hyprpaper.conf"
        if hp_conf.parent.exists():
            hp_conf.write_text(
                f"wallpaper {{\n    monitor =\n    path = {wall}\n    fit_mode = cover\n}}\nsplash = false\n",
                encoding="utf-8",
            )
            subprocess.Popen(
                f"pkill -x owe-render; pkill -x owed; pkill -x hyprpaper; sleep 0.15; "
                f"setsid hyprpaper -c '{hp_conf}' >/dev/null 2>&1 &",
                shell=True,
                start_new_session=True,
            )

    accent_hex = palette["accent"].lstrip("#")
    surface_hex = palette["surface"].lstrip("#")
    subprocess.Popen(
        f"hyprctl keyword general:col.active_border 'rgba({accent_hex}ee)' >/dev/null 2>&1; "
        f"hyprctl keyword general:col.inactive_border 'rgba({surface_hex}aa)' >/dev/null 2>&1",
        shell=True,
        start_new_session=True,
    )

    # Restart Orbit Shell so top & bottom bars pick up the new palette immediately
    shell_bin = Path.home() / ".local" / "bin" / "orbit-shell"
    if shell_bin.exists():
        subprocess.Popen(
            f"pkill -f '[o]rbit_suite\\.shell'; sleep 0.2; setsid '{shell_bin}' >/tmp/orbit-shell.log 2>&1 &",
            shell=True,
            start_new_session=True,
        )


def discover_wallpapers() -> list[Path]:
    dirs = [
        Path.home() / "Pictures" / "Wallpapers",
        Path.home() / ".local" / "state" / "omarchy" / "current" / "theme" / "backgrounds",
        Path("/usr/share/backgrounds"),
    ]
    found: list[Path] = []
    seen: set[str] = set()
    for d in dirs:
        if not d.is_dir():
            continue
        for p in sorted(d.iterdir()):
            if p.is_file() and p.suffix.lower() in IMAGE_EXTS and p.name not in seen:
                seen.add(p.name)
                found.append(p)
    return found


class OrbitThemeWindow(Adw.ApplicationWindow):
    """Wallpaper & dynamic pywal-style theme picker."""

    def __init__(self, app: Adw.Application) -> None:
        super().__init__(application=app, title=APP_NAME)
        self.set_default_size(820, 560)

        self._toast = Adw.ToastOverlay()
        self.set_content(self._toast)

        tv = Adw.ToolbarView()
        self._toast.set_child(tv)

        header = Adw.HeaderBar()

        pick_btn = Gtk.Button.new_with_label("Choose File…")
        pick_btn.connect("clicked", self._on_pick_file)
        header.pack_start(pick_btn)

        reset_btn = Gtk.Button.new_with_label("Reset Dracula")
        reset_btn.connect("clicked", self._on_reset_dracula)
        header.pack_end(reset_btn)
        tv.add_top_bar(header)

        scrolled = Gtk.ScrolledWindow()
        scrolled.set_policy(Gtk.PolicyType.NEVER, Gtk.PolicyType.AUTOMATIC)

        flow = Gtk.FlowBox()
        flow.set_valign(Gtk.Align.START)
        flow.set_max_children_per_line(4)
        flow.set_selection_mode(Gtk.SelectionMode.NONE)
        flow.set_row_spacing(12)
        flow.set_column_spacing(12)
        flow.set_margin_top(14)
        flow.set_margin_bottom(14)
        flow.set_margin_start(14)
        flow.set_margin_end(14)

        for wall in discover_wallpapers():
            flow.append(self._make_card(wall))

        scrolled.set_child(flow)
        tv.set_content(scrolled)

    def _make_card(self, wall: Path) -> Gtk.Button:
        btn = Gtk.Button()
        btn.add_css_class("flat")
        box = Gtk.Box(orientation=Gtk.Orientation.VERTICAL, spacing=6)

        pic = Gtk.Picture()
        pic.set_size_request(170, 100)
        pic.set_content_fit(Gtk.ContentFit.COVER)
        try:
            pb = GdkPixbuf.Pixbuf.new_from_file_at_scale(str(wall), 200, 120, True)
            pic.set_paintable(Gdk.Texture.new_for_pixbuf(pb))
        except Exception:
            pass
        box.append(pic)

        lbl = Gtk.Label(label=wall.stem)
        lbl.set_ellipsize(3)
        lbl.set_max_width_chars(20)
        lbl.add_css_class("caption")
        box.append(lbl)

        btn.set_child(box)
        btn.connect("clicked", lambda _b, w=wall: self._apply_wallpaper(w))
        return btn

    def _apply_wallpaper(self, wall: Path) -> None:
        pal = extract_palette(wall)
        apply_live(pal)
        self._toast.add_toast(Adw.Toast.new(f"Applied wallpaper & palette: {wall.stem}"))

    def _on_reset_dracula(self, _btn: Gtk.Button) -> None:
        apply_live(DRACULA_PALETTE)
        self._toast.add_toast(Adw.Toast.new("Reset Orbit palette to Dracula"))

    def _on_pick_file(self, _btn: Gtk.Button) -> None:
        dlg = Gtk.FileDialog.new()
        dlg.set_title("Choose Wallpaper")

        def _done(d: Gtk.FileDialog, res: Gio.AsyncResult) -> None:
            try:
                f = d.open_finish(res)
                if f and f.get_path():
                    self._apply_wallpaper(Path(f.get_path()))
            except GLib.Error:
                pass

        dlg.open(self, None, _done)


class OrbitThemeApp(Adw.Application):
    def __init__(self) -> None:
        super().__init__(application_id=APP_ID)

    def do_startup(self) -> None:
        Adw.Application.do_startup(self)
        load_css_string("")

    def do_activate(self) -> None:
        win = self.get_active_window()
        if win is None:
            win = OrbitThemeWindow(self)
        win.present()


def main(argv: list[str] | None = None) -> int:
    args = (argv if argv is not None else sys.argv)[1:]
    if "--reset-dracula" in args:
        apply_live(DRACULA_PALETTE)
        print("Reset Orbit palette to Dracula.")
        return 0
    if args and not args[0].startswith("-"):
        wall = Path(args[0]).expanduser().resolve()
        pal = extract_palette(wall)
        apply_live(pal)
        print(f"Applied palette from {wall.name}: accent={pal['accent']} accent2={pal['accent2']}")
        return 0
    app = OrbitThemeApp()
    return app.run(argv if argv is not None else sys.argv)


if __name__ == "__main__":
    raise SystemExit(main())
